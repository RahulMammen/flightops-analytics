"""Command line entry point.

    python -m flightops.cli generate     # synthetic raw CSV + separate defect labels -> data/raw
    python -m flightops.cli run          # ingest, validate, transform, export Parquet, write reports
    python -m flightops.cli all          # both
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

from . import metrics
from .generate import GeneratorConfig, write_dataset
from .pipeline import REASON_CODES, connect, export_parquet, ingest, transform


def run_pipeline(raw_csv: Path, db_path: Path, processed_dir: Path, reports_dir: Path,
                 labels_csv: Path | None) -> dict:
    con = connect(db_path)
    try:
        ing = ingest(con, raw_csv)
        recon = transform(con)
        files = export_parquet(con, processed_dir)
        summary = metrics.summary(con)
        turns = metrics.turnaround_stats(con)
        routes = metrics.route_performance(con)
        reports_dir.mkdir(parents=True, exist_ok=True)
        routes.to_csv(reports_dir / "route_performance.csv", index=False)
        report = {
            "dataset": "SYNTHETIC fictional airline data generated by flightops.generate",
            "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
            "ingestion": ing,
            "ingestion_log": con.execute("SELECT batch_id, file_name, rows_in_file, rows_inserted, "
                                         "rows_already_present FROM ingestion_log ORDER BY batch_id"
                                         ).fetchdf().to_dict(orient="records"),
            "reconciliation": recon,
            "reason_code_definitions": REASON_CODES,
            "summary": {k: (round(v, 4) if isinstance(v, float) else v) for k, v in summary.items()},
            "turnarounds": {
                "status_counts": dict(turns["status_counts"].values.tolist()),
                "ok": {k: round(float(v), 2) for k, v in turns["ok"].items()},
            },
            "parquet_files": files,
        }
        if labels_csv and labels_csv.exists():
            det = metrics.defect_detection(con, str(labels_csv))
            det.to_csv(reports_dir / "defect_detection.csv", index=False)
            report["defect_detection"] = det.to_dict(orient="records")
        (reports_dir / "pipeline_report.json").write_text(json.dumps(report, indent=2, default=str))
        return report
    finally:
        con.close()


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="flightops")
    p.add_argument("cmd", choices=["generate", "run", "all"])
    p.add_argument("--raw-dir", type=Path, default=Path("data/raw"))
    p.add_argument("--db", type=Path, default=Path("data/warehouse/flightops.duckdb"))
    p.add_argument("--processed-dir", type=Path, default=Path("data/processed"))
    p.add_argument("--reports-dir", type=Path, default=Path("reports"))
    p.add_argument("--seed", type=int, default=GeneratorConfig.seed)
    args = p.parse_args(argv)

    if args.cmd in ("generate", "all"):
        info = write_dataset(args.raw_dir, GeneratorConfig(seed=args.seed))
        print(json.dumps({"generated": info}, indent=2))
    if args.cmd in ("run", "all"):
        report = run_pipeline(args.raw_dir / "flights_raw.csv", args.db, args.processed_dir,
                              args.reports_dir, args.raw_dir / "injected_defects.csv")
        print(json.dumps({k: report[k] for k in ("ingestion", "reconciliation", "summary")}, indent=2))


if __name__ == "__main__":
    main()
